    profit_margin = (
        profit / revenue * 100
        if revenue > 0
        else 0
    )

    average_order_value = (
        revenue / transactions
        if transactions > 0
        else 0
    )

    complaint_rate = (
        complaints / customers * 100
        if customers > 0
        else 0
    )

    marketing_ratio = (
        marketing / revenue * 100
        if revenue > 0
        else 0
    )

    return {
        "Profit":
            round(profit, 2),
        "Profit Margin %":
            round(profit_margin, 2),
        "Average Order Value":
            round(average_order_value, 2),
        "Complaint Rate %":
            round(complaint_rate, 2),
        "Marketing / Revenue %":
            round(marketing_ratio, 2)
    }


