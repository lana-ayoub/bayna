def get_valid_performance_df():
    if (
        performance_df is None
        or performance_df.empty
    ):
        return pd.DataFrame()

    temp = performance_df.copy()

    required = [
        "Revenue",
        "Expenses",
        "Customers",
        "Transactions"
    ]

    for col in required:
        if col not in temp.columns:
            temp[col] = 0

    actual_mask = (
        temp[required]
        .fillna(0)
        .abs()
        .sum(axis=1)
        > 0
    )

    temp = temp[
        actual_mask
    ].copy()

    if temp.empty:
        return temp

    temp["Month Order"] = (
        temp["Month"]
        .apply(get_month_number)
    )

    return (
        temp
        .sort_values("Month Order")
        .reset_index(drop=True)
    )


