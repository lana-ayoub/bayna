def detect_review_aspects(review):
    text = str(review).lower()
    found_aspects = []

    for aspect, keywords in (
        aspect_keywords.items()
    ):
        for keyword in keywords:
            if keyword.lower() in text:
                found_aspects.append(
                    aspect
                )
                break

    if not found_aspects:
        found_aspects.append(
            "غير محدد"
        )

    return found_aspects


def split_review_into_clauses(review):
    text = str(review).strip()

    clauses = re.split(
        r"\s*(?:بس|لكن|ولكن|،|,|؛|;)\s*|\s+و(?=ال)",
        text
    )

    return [
        clause.strip()
        for clause in clauses
        if clause.strip()
    ]


def analyze_aspect_sentiment(review):
    results = []

    for clause in split_review_into_clauses(
        review
    ):
        aspects = detect_review_aspects(
            clause
        )

        if aspects == ["غير محدد"]:
            continue

        sentiment = analyze_review_sentiment(
            clause
        )

        for aspect in aspects:
            results.append({
                "Review":
                    review,
                "Aspect":
                    aspect,
                "Context":
                    clause,
                "Aspect Sentiment":
                    sentiment["Sentiment"],
                "Confidence":
                    sentiment["Confidence"]
            })

    return results


def build_aspect_summary(reviews):
    aspect_results = []

    for review in reviews:
        aspect_results.extend(
            analyze_aspect_sentiment(
                review
            )
        )

    if not aspect_results:
        return pd.DataFrame()

    df = pd.DataFrame(
        aspect_results
    )

    summary = (
        df
        .groupby(
            ["Aspect", "Aspect Sentiment"]
        )
        .size()
        .unstack(fill_value=0)
    )

    for sentiment in [
        "إيجابي",
        "محايد",
        "سلبي"
    ]:
        if sentiment not in summary.columns:
            summary[sentiment] = 0

    summary = summary[
        ["إيجابي", "محايد", "سلبي"]
    ]

    summary["Total Mentions"] = (
        summary[
            ["إيجابي", "محايد", "سلبي"]
        ]
        .sum(axis=1)
    )

    summary["Positive %"] = (
        summary["إيجابي"]
        / summary["Total Mentions"]
        * 100
    )

    summary["Negative %"] = (
        summary["سلبي"]
        / summary["Total Mentions"]
        * 100
    )

    confidence_summary = (
        df
        .groupby("Aspect")[
            "Confidence"
        ]
        .mean()
    )

    summary["Average Confidence"] = (
        confidence_summary
    )

    return (
        summary
        .sort_values(
            ["Negative %", "Total Mentions"],
            ascending=[False, False]
        )
        .reset_index()
    )


