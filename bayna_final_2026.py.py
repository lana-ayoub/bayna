def safe_percent_change(
    current,
    previous
):
    try:
        current = float(current)
        previous = float(previous)
    except Exception:
        return None

    if previous == 0 and current == 0:
        return 0.0

    if previous == 0:
        return None

    return (
        (current - previous)
        / abs(previous)
        * 100
    )


def format_change(value):
    if value is None or pd.isna(value):
        return "N/A"

    return f"{value:+.1f}%"


def build_current_month_comparison(
    previous,
    latest
):
    indicators = [
        "Revenue",
        "Expenses",
        "Profit",
        "Profit Margin %",
        "Customers",
        "Transactions",
        "Average Order Value",
        "Complaints",
        "Complaint Rate %",
        "Marketing Spend",
        "Marketing / Revenue %",
        "Customer Rating"
    ]

    rows = []

    for indicator in indicators:
        old_value = float(
            previous[indicator]
        )
        new_value = float(
            latest[indicator]
        )

        difference = (
            new_value - old_value
        )

        change = safe_percent_change(
            new_value,
            old_value
        )

        rows.append({
            "Indicator":
                indicator,
            "Previous":
                old_value,
            "Current":
                new_value,
            "Difference":
                difference,
            "Change %":
                np.nan
                if change is None
                else change
        })

    return pd.DataFrame(rows)


